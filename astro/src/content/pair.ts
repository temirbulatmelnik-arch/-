/** группировка аспектов синастрии */
export function synGroup(a: string, b: string, aspect: string): 'bond' | 'friction' | 'karma' {
  const karmic = ['node', 'snode', 'saturn', 'chiron', 'vertex', 'pluto'];
  if (karmic.includes(a) || karmic.includes(b)) return 'karma';
  if (['square', 'opp', 'quincunx', 'semisq', 'sesq'].includes(aspect)) return 'friction';
  return 'bond';
}

