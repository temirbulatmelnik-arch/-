/** Короткий цикл каждого упражнения — его 3D-фигура повторяет по кругу */
const DEMO: Record<BlockType, Block> = {
  breath: { type: 'breath', cycles: 1, inhale: 4, exhale: 6 },
  slow: { type: 'slow', reps: 1, hold: 4, rest: 4 },
  quick: { type: 'quick', reps: 3, on: 1, off: 1.5 },
  lift: { type: 'lift', reps: 1, floor: 2, rest: 2 },
  endurance: { type: 'endurance', reps: 1, hold: 6, rest: 4, intensity: 0.5 },
  release: { type: 'release', cycles: 1, inhale: 4, exhale: 6 },
};

export function demoTimeline(type: BlockType, position: Position = 'sitting'): Timeline {
  const level: Level = { id: 0, name: '', subtitle: '', position, minSessions: Infinity, blocks: [DEMO[type]] };
  return buildTimeline(level, { blocksOnly: true });
}
