/** Какое движение показывает 3D-фигура */
export type Anim =
  | 'nod' | 'nodPress' | 'headLift' | 'er' | 'sideFlex' | 'scapSet' | 'proneT' | 'proneY' | 'proneW' | 'proneExt'
  | 'plus' | 'angel' | 'doorway' | 'trapStretch' | 'scmStretch' | 'chairExt' | 'thread' | 'breath' | 'walk' | 'screen'
  | 'ctar' | 'tongueTip' | 'tongueBack' | 'jawOpen' | 'chew' | 'clench' | 'smile'
  | 'platysma' | 'jawJut' | 'kissCeiling' | 'shaker' | 'mewing';

export interface Guide {
  goal: string;
  steps: string[];
  breath: string;
  feel: string;
  mistakes: string[];
}

export interface Exercise {
  id: string;
  block: BlockId;
  title: string;
  /** одна строка под названием */
  short: string;
  /** коротко как делать — показывается в подготовке */
  how: string;
  pose: Pose;
  anim: Anim;
  muscles: MuscleMap;
  guide: Guide;
  /** что сказать голосом перед первым повтором */
  voice: string;
  /** слова на каждый повтор: начало движения, удержание, возврат */
  words?: { up?: string; hold?: string; down?: string };
  /** откуда доза и выбор упражнения */
  evidence?: string;
  /** упражнение на одну сторону: делается по очереди */
  sided?: boolean;
  /** нагружает челюсть — только если опросник ВНЧС чистый */
  jaw?: boolean;
}

